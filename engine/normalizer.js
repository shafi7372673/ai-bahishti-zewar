/**
 * ٹوکنز الگ کرنا
 */
function tokenizeUrdu(text) {
  const norm = normalizeUrdu(text);
  if (!norm) return [];
  return norm.split(' ').filter(w => w.length > 0);
}

/**
 * سوال کو تجزیہ کرنا اور صرف با معنی الفاظ نکالنا
 */
function expandQuery(query) {
  const normQuery = normalizeUrdu(query);
  const allTokens = tokenizeUrdu(query);
  
  // صرف با معنی الفاظ رکھیں (اسٹاپ ورڈز کو سختی سے ہٹا دیں)
  const significantTokens = allTokens.filter(t => !STOPWORDS.has(t) && t.length > 1);

  const expandedConceptTerms = new Set();

  // مترادفات چیک کریں
  for (const [key, synonyms] of Object.entries(SYNONYM_MAP)) {
    const normKey = normalizeUrdu(key);
    if (normQuery.includes(normKey)) {
      expandedConceptTerms.add(normKey);
      synonyms.forEach(syn => {
        expandedConceptTerms.add(normalizeUrdu(syn));
      });
    }
  }

  // انفرادی ٹوکنز کے ذریعے بھی مترادفات شامل کریں اگر مطابقت ہو
  significantTokens.forEach(tok => {
    for (const [key, synonyms] of Object.entries(SYNONYM_MAP)) {
      const normKeyTokens = tokenizeUrdu(key);
      if (normKeyTokens.includes(tok)) {
        expandedConceptTerms.add(normalizeUrdu(key));
        synonyms.forEach(syn => {
          expandedConceptTerms.add(normalizeUrdu(syn));
        });
      }
    }
  });

  return {
    original: query,
    normalized: normQuery,
    allTokens,
    significantTokens,
    expandedTerms: Array.from(expandedConceptTerms).filter(t => !STOPWORDS.has(t))
  };
}

